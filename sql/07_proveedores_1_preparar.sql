-- 1) Por código
UPDATE import_proveedores i SET product_id = p.id, metodo = 'codigo', similitud = 1
FROM products p
WHERE i.codigo IS NOT NULL AND p.sku IS NOT NULL AND trim(p.sku) = i.codigo;

-- 2) Por nombre igual (si hay más de un artículo con el mismo nombre, se toma el de menor id)
UPDATE import_proveedores i SET product_id = m.id, metodo = 'nombre', similitud = 1
FROM (
  SELECT DISTINCT ON (pg_temp.norm(name)) id, pg_temp.norm(name) AS n FROM products ORDER BY pg_temp.norm(name), id
) m
WHERE i.product_id IS NULL AND m.n = pg_temp.norm(i.detalle) AND m.n <> '';

-- 3) Por nombre parecido: el más parecido, si llega al 70% y ese artículo no quedó ya tomado
UPDATE import_proveedores i SET product_id = b.pid, metodo = 'parecido', similitud = round(b.sim::numeric, 2)
FROM (
  SELECT DISTINCT ON (i2.id) i2.id AS iid, p.id AS pid, similarity(pg_temp.norm(p.name), pg_temp.norm(i2.detalle)) AS sim
  FROM import_proveedores i2
  JOIN products p ON pg_temp.norm(p.name) % pg_temp.norm(i2.detalle)
  WHERE i2.product_id IS NULL
  ORDER BY i2.id, sim DESC, p.id
) b
WHERE i.id = b.iid AND b.sim >= 0.70
  AND NOT EXISTS (SELECT 1 FROM import_proveedores x WHERE x.product_id = b.pid AND x.metodo IN ('codigo','nombre'));

-- Un mismo artículo en las listas de dos proveedores: se queda el primero (por código/nombre) y el otro no se aplica
UPDATE import_proveedores i SET aplicar = FALSE
WHERE product_id IS NOT NULL AND EXISTS (
  SELECT 1 FROM import_proveedores o
  WHERE o.product_id = i.product_id AND o.id <> i.id
    AND (o.metodo < i.metodo OR (o.metodo = i.metodo AND (o.similitud > i.similitud OR (o.similitud = i.similitud AND o.id < i.id))))
);

-- ─── RESUMEN ────────────────────────────────────────────────────────
SELECT proveedor,
       COUNT(*)                                            AS filas_excel,
       COUNT(*) FILTER (WHERE metodo IN ('codigo','nombre')) AS seguros,
       COUNT(*) FILTER (WHERE metodo = 'parecido')         AS para_revisar,
       COUNT(*) FILTER (WHERE product_id IS NULL)          AS no_encontrados
FROM import_proveedores GROUP BY proveedor ORDER BY proveedor;

-- ─── PARA REVISAR: nombres parecidos (si alguno está mal, ver al final cómo excluirlo) ───
SELECT i.id, i.proveedor, i.detalle AS en_excel, p.name AS en_el_sistema, i.similitud
FROM import_proveedores i JOIN products p ON p.id = i.product_id
WHERE i.metodo = 'parecido' ORDER BY i.similitud, i.proveedor;

-- ─── NO ENCONTRADOS en el sistema (no se hace nada con ellos) ───
SELECT proveedor, detalle FROM import_proveedores WHERE product_id IS NULL ORDER BY proveedor, detalle;

