--   1) por CÓDIGO (sku)            → seguro
--   2) por NOMBRE igual            → seguro (sin importar mayúsculas, acentos o signos)
--   3) por NOMBRE PARECIDO (≥ 70%) → para revisar
-- Al final muestra el resumen y las listas para revisar.
-- Se puede correr las veces que haga falta. Después: 07_proveedores_2_aplicar.sql
