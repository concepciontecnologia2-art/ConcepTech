CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- Normaliza un nombre para comparar: minúsculas, sin acentos ni signos, sin las marcas WWW/ZZZ del sistema viejo
CREATE OR REPLACE FUNCTION pg_temp.norm(t text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
  SELECT trim(regexp_replace(regexp_replace(
           translate(lower(coalesce(t,'')), 'áéíóúüàèìòù', 'aeiouuaeiou'),
           '^(www|zzz)\s+', ''), '[^a-z0-9ñ]+', ' ', 'g'))
$$;

